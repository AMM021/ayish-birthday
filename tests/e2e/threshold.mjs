import { launch, BASE, sleep } from './lib.mjs';
const out = process.argv[2];
const { browser, page, logs } = await launch();
await page.goto(BASE + '?dev=true', { waitUntil: 'load' });
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('ayish.progress', JSON.stringify({unlocked:true})); });
await page.goto(BASE + '?dev=true', { waitUntil: 'load' }); await sleep(2000);
const G = (f) => page.evaluate(f);
await G(() => window.__game.machine.go('THRESHOLD')); await sleep(2500);
console.log('state', await G(()=>window.__game.machine.currentName), 'line:', await G(()=>document.querySelector('.overlay-line')?.textContent));
await page.screenshot({ path: out + '/threshold.png' });
const p0 = await G(()=>window.__game.world.camera.position.toArray());
await page.keyboard.down('KeyW'); await sleep(800); await page.keyboard.up('KeyW');
const p1 = await G(()=>window.__game.world.camera.position.toArray());
console.log('moved with W:', p0.map(v=>v.toFixed(2)).join(','), '→', p1.map(v=>v.toFixed(2)).join(','));
await sleep(3500);
console.log('controls hint shown:', await G(()=>document.querySelector('.prompt-controls').classList.contains('show')), 'look hint:', await G(()=>document.querySelector('.prompt-look').classList.contains('show')));
// teleport to door
const tp = (x,z) => G(new Function(`const w=window.__game.world; w.setPlayer(new w.camera.position.constructor(${x},1.6,${z}), Math.PI/2, 0);`));
await tp(-2.8,-0.8); await sleep(800);
console.log('note open:', await G(()=>!!document.querySelector('.overlay-note')));
await sleep(1500);
await page.screenshot({ path: out + '/note.png' });
await page.keyboard.press('Enter'); await sleep(200);
console.log('after 1 Enter: still open', await G(()=>!!document.querySelector('.overlay-note')), 'text complete:', await G(()=>document.querySelector('.note-text').textContent.endsWith('lub dub')));
await page.keyboard.press('Enter'); await sleep(900);
console.log('after 2nd Enter: closed', await G(()=>!document.querySelector('.overlay-note')));
await sleep(1500);
console.log('stayed in range, note reopened?', await G(()=>!!document.querySelector('.overlay-note')), 'state', await G(()=>window.__game.machine.currentName));
await tp(0.5,1.5); await sleep(500);
await tp(-2.8,-0.8); await sleep(3000);
console.log('second approach → state', await G(()=>window.__game.machine.currentName));
console.log(logs.filter(l=>!l.includes('vite')).join('\n'));
await browser.close();
