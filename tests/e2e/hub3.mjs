import { launch, BASE, sleep, jump, bubbleState, waitFor, drainStory } from './lib.mjs';
const out = process.argv[2];
const { browser, page, logs } = await launch();
await page.goto(BASE + '?dev=true', { waitUntil: 'load' });
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('ayish.progress', JSON.stringify({unlocked:true})); });
await page.goto(BASE + '?dev=true', { waitUntil: 'load' });
const G = (f, ...a) => page.evaluate(f, ...a);
const tp = (x,y,z) => G((x,y,z)=>{const w=window.__game.world; w.camera.position.set(x,y,z); w.player.prev.set(x,y,z);}, x,y,z);
const gp = (deg,k=1) => { const a=deg*Math.PI/180; return [Math.sin(a)*18*k, 1.6, -Math.cos(a)*18*k]; };
const anyBubble = async () => { await waitFor(page, ()=>!!document.querySelector('.bubble.show'), 8000); return (await bubbleState(page))[0]?.full; };
await jump(page, 'HUB');
await page.screenshot({ path: out + '/hub.png' });
console.log('intro beats drained:', await drainStory(page));
await tp(...gp(-30,0.55));
console.log('second bubble:', await anyBubble());
await drainStory(page); await sleep(500);
await tp(...gp(-30,0.95)); await sleep(300); await tp(...gp(-30));
console.log('locked compile gate:', await anyBubble(), '| state', await G(()=>window.__game.machine.currentName));
await page.screenshot({ path: out + '/hub-locked.png' });
await waitFor(page, ()=>!document.querySelector('.bubble'), 20000);
await tp(...gp(0,0.6)); await sleep(500); await tp(...gp(0,0.97));
console.log('door5:', await anyBubble());
await waitFor(page, ()=>!document.querySelector('.bubble'), 20000);
await tp(...gp(-60,0.7)); await sleep(500); await tp(...gp(-60));
await waitFor(page, ()=>window.__game.machine.currentName==='TORII', 8000);
console.log('open torii gate → state', await G(()=>window.__game.machine.currentName));
// return with torii done → compile opens, returning line
await G(()=>window.__game.save.setRoomDone('torii'));
await jump(page, 'HUB');
console.log('returning line:', await anyBubble());
console.log('gate states:', await G(()=>{ return 'n/a'; }));
await page.screenshot({ path: out + '/hub-return.png' });
console.log(logs.filter(l=>!l.includes('vite')).join('\n'));
await browser.close();
