import { launch, BASE, sleep, jump, drainStory, waitFor, bubbleState } from './lib.mjs';
const out = process.argv[2];
const { browser, page, logs } = await launch();
await page.goto(BASE + '?dev=true', { waitUntil: 'load' });
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('ayish.progress', JSON.stringify({unlocked:true, roomsDone:['torii','compile','stars']})); });
await page.goto(BASE + '?dev=true', { waitUntil: 'load' });
const D = () => page.evaluate(() => window.__game.machine.current._debug());
const tp = (p) => page.evaluate((p)=>{const w=window.__game.world; w.camera.position.set(...p); w.player.prev.set(...p);}, p);
await jump(page, 'PETALS'); await sleep(2000);
await page.evaluate(()=>{ const d=document.querySelector('.devtools'); if(d) d.style.display='none'; });
await page.screenshot({ path: out + '/petals.png' });
let d = await D();
const inBounds = d.waypoints.every(w => Math.hypot(...w) < 100 && Math.abs(w[0]) <= 10 && Math.abs(w[2]) <= 40);
console.log('mode before intro done:', d.mode, '| waypoints in bounds & corridor:', inBounds);
await drainStory(page);
await sleep(1500); d = await D(); console.log('after intro → mode', d.mode);
// stay put; orb should pause once >15 away
await waitFor(page, () => window.__game.machine.current._debug().mode === 'paused', 60000);
d = await D(); console.log('she stays → mode', d.mode, 'lost line:', (await bubbleState(page))[0]?.full);
// go far back → returning
await tp([0, 2.2, 39]); 
await page.evaluate(()=>{ const o=window.__game.orb; }); 
await waitFor(page, () => { const g=window.__game; const o=g.orb.position, c=g.world.camera.position; return o.distanceTo(c) > 30 || g.machine.current._debug().mode==='returning'; }, 30000);
await waitFor(page, () => window.__game.machine.current._debug().mode === 'returning', 30000);
d = await D(); console.log('far behind → mode', d.mode);
await waitFor(page, () => window.__game.machine.current._debug().mode === 'lead', 60000);
d = await D(); console.log('orb came back → mode', d.mode);
await tp([0, 2.2, -36]); await sleep(1500);
d = await D(); console.log('reached end → done', d.done, 'portal', d.portal, 'line:', (await bubbleState(page))[0]?.full);
console.log('save', await page.evaluate(()=>localStorage.getItem('ayish.progress')));
await drainStory(page);
await tp([0, 2.6, -37.5]); 
await waitFor(page, () => window.__game.machine.currentName === 'HUB', 10000);
console.log('portal → state', await page.evaluate(()=>window.__game.machine.currentName));
await sleep(3000);
await page.evaluate(()=>{ const d=document.querySelector('.devtools'); if(d) d.style.display='none'; });
console.log('hub line:', (await bubbleState(page))[0]?.full);
await page.screenshot({ path: out + '/hub-all.png' });
console.log(logs.filter(l=>!l.includes('vite')).join('\n'));
await browser.close();
